import test from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import pg from 'pg';
import pool from '../db/connection.js';
import {migrateAccountAccess} from '../services/accountMigration.js';
import {migrateNofoForms} from '../services/forms/formMigration.js';
import {applicationFormContext,saveFormApplication} from '../services/forms/applicationFormSave.js';
import {readNofoForm,saveNofoForm} from '../services/forms/formVersions.js';
import {readNofoProgramDefaults} from '../services/forms/programFormDefaults.js';
import {saveProgramForm} from '../services/forms/programFormVersions.js';
import {readProgramForm} from '../services/forms/programFormDefaults.js';
import {formFields} from '../../src/lib/forms/defaultForm.js';
test('First activation preserves legacy drafts and applying program defaults creates a later version',async()=>{
  const schema='gmt_qa_legacy_forms_'+Date.now();await pool.query('CREATE SCHEMA '+schema);
  const db=new pg.Pool({...pool.options,options:'-c search_path='+schema+',public'});
  try {
    for(const table of ['users','organizations','grantees','audit_logs','grant_programs','nofos','applications','application_budgets','documents','notifications'])await db.query('CREATE TABLE '+table+' (LIKE public.'+table+' INCLUDING ALL)');
    await migrateAccountAccess(db);
    const [admin,user,org,program,nofo,app]=Array.from({length:6},()=>randomUUID());
    await db.query("INSERT INTO organizations(id,name,type,state) VALUES($1,'Legacy QA County','County','NE')",[org]);
    await db.query("INSERT INTO users(id,email,password_hash,role,scope_state,organization_id,active_status) VALUES($1,'legacy-admin@gmt-qa.invalid','synthetic','isc_admin',null,null,'active'),($2,'legacy-user@gmt-qa.invalid','synthetic','user','NE',$3,'active')",[admin,user,org]);
    await db.query("INSERT INTO grant_programs(id,name,code,is_active) VALUES($1,'Legacy QA EMPG','EMPG',true)",[program]);
    await db.query("INSERT INTO nofos(id,title,program_id,program_code,status,scope_states,required_documents) VALUES($1,'Legacy QA NOFO',$2,'EMPG','Published','[\"NE\"]','[]')",[nofo,program]);
    await db.query("INSERT INTO applications(id,nofo_id,organization_id,project_title,requested_amount,status) VALUES($1,$2,$3,'Preexisting work',123.45,'Draft')",[app,nofo,org]);
    await migrateNofoForms(db);
    const old=await applicationFormContext(db,user,app,'edit'),oldFields=formFields(old.version.definition);
    assert.equal(old.version.definition.legacy,true);assert.ok(old.version.locked_at);
    assert.ok(!oldFields.some(field=>field.id==='cf_empg_personnel'));
    assert.equal(oldFields.find(field=>field.key==='project_title').required,false);
    assert.equal(oldFields.find(field=>field.key==='requested_amount').label,'Requested Amount ($)');
    assert.equal(oldFields.find(field=>field.key==='ehp_notes').label,'Additional EHP Notes (optional)');
    await migrateNofoForms(db);
    assert.equal((await db.query('SELECT COUNT(*)::int count FROM nofo_form_versions')).rows[0].count,1);
    const preserved=(await db.query('SELECT project_title,requested_amount,status FROM applications WHERE id=$1',[app])).rows[0];
    assert.deepEqual(preserved,{project_title:'Preexisting work',requested_amount:'123.45',status:'Draft'});
    const modern=await readNofoProgramDefaults(db,admin,nofo),current=await readNofoForm(db,admin,nofo);
    assert.ok(formFields(modern.definition).some(field=>field.id==='cf_empg_personnel'));
    const updated=await saveNofoForm(db,admin,nofo,{definition:modern.definition,expectedVersionId:current.id,expectedRevision:current.revision,appliedProgramDefaultId:modern.program_default_version_id});
    assert.equal(updated.version,2);assert.equal(updated.definition.legacy,undefined);
    assert.equal((await applicationFormContext(db,user,app,'edit')).version.id,old.version.id);
    const next=await saveFormApplication(db,user,null,{nofo_id:nofo,organization_id:org});
    assert.equal(next.form_version_id,updated.id);
    const p=await readProgramForm(db,admin,program);
    const pv=await saveProgramForm(db,admin,program,{definition:p.definition,scope_state:'',expectedVersionId:p.id,expectedRevision:p.revision});
    await assert.rejects(saveNofoForm(db,admin,nofo,{definition:modern.definition,expectedVersionId:updated.id,expectedRevision:updated.revision,appliedProgramDefaultId:null}),{status:409});
    const latest=await readNofoProgramDefaults(db,admin,nofo);
    const newest=await saveNofoForm(db,admin,nofo,{definition:latest.definition,expectedVersionId:updated.id,expectedRevision:updated.revision,appliedProgramDefaultId:latest.program_default_version_id});
    assert.equal(newest.program_default_version_id,pv.id);
    await migrateNofoForms(db);
    assert.equal((await applicationFormContext(db,user,app,'edit')).version.id,old.version.id);
  }finally {await db.end();await pool.query('DROP SCHEMA '+schema+' CASCADE');await pool.end();}
});
